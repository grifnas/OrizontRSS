using System.Net;
using System.Net.Http;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using System.Xml.Linq;
using CititorRSS.Jaws.Localization;
using static CititorRSS.Jaws.Services.Rss.YouTubeCommon;

namespace CititorRSS.Jaws.Services.Rss;

/// <summary>
/// Obține transcriptul unui videoclip YouTube fără cheie API, folosind pagina publică a videoclipului.
/// </summary>
internal static class YouTubeTranscriptService
{
    private const string PlayerResponseMarker = "ytInitialPlayerResponse = ";
    private const string AndroidClientVersion = "20.10.38";
    private static readonly HttpClient Client = CreateClient();

    // ───────────────────────────────────────────────
    // Model public
    // ───────────────────────────────────────────────

    /// <summary>
    /// Reprezentarea unui track de subtitrare disponibil pentru un videoclip YouTube.
    /// </summary>
    internal sealed record TranscriptTrack(
        string LanguageCode,
        string LanguageName,
        string BaseUrl,
        bool IsAutoGenerated)
    {
        /// <summary>
        /// Eticheta afișată în interfață: numele limbii, cu indicatorul ASR dacă e generat automat.
        /// </summary>
        public string DisplayName => IsAutoGenerated
            ? UiText.Format("{0} (generat automat)", LanguageName)
            : LanguageName;
    }

    // ───────────────────────────────────────────────
    // API public
    // ───────────────────────────────────────────────

    /// <summary>
    /// Returnează lista de track-uri de subtitrare disponibile pentru videoclipul dat.
    /// Aruncă <see cref="InvalidOperationException"/> dacă videoclipul nu are subtitrări.
    /// </summary>
    internal static Task<List<TranscriptTrack>> GetAvailableTracksAsync(
        string videoId,
        CancellationToken cancellationToken = default) =>
        GetAvailableTracksAsync(videoId, Client, cancellationToken);

    internal static async Task<List<TranscriptTrack>> GetAvailableTracksAsync(
        string videoId,
        HttpClient client,
        CancellationToken cancellationToken = default)
    {
        // 1) Interogarea Innertube cu clientul Android: adresele de subtitrare returnate nu cer jeton PO
        //    și nu depind de pagina de consimțământ afișată utilizatorilor din UE.
        try
        {
            return await GetTracksFromInnertubeAsync(videoId, client, cancellationToken).ConfigureAwait(false);
        }
        catch (Exception) when (!cancellationToken.IsCancellationRequested)
        {
            // Continuăm cu pagina publică a videoclipului.
        }

        // 2) Varianta de rezervă: pagina publică a videoclipului.
        var url = $"https://www.youtube.com/watch?v={Uri.EscapeDataString(videoId)}&hl=en&bpctr=9999999999&has_verified=1";
        using var request = new HttpRequestMessage(HttpMethod.Get, url);
        request.Headers.Accept.ParseAdd("text/html,application/xhtml+xml");
        request.Headers.AcceptLanguage.ParseAdd("en;q=0.9");

        using var response = await client.SendAsync(request, HttpCompletionOption.ResponseHeadersRead, cancellationToken).ConfigureAwait(false);
        if (response.StatusCode is HttpStatusCode.TooManyRequests or HttpStatusCode.ServiceUnavailable)
            throw new InvalidOperationException(UiText.Translate("YouTube a limitat temporar accesul. Încearcă din nou mai târziu."));
        if (!response.IsSuccessStatusCode)
            throw new HttpRequestException(UiText.Format("YouTube a răspuns cu eroarea {0}.", (int)response.StatusCode));

        var html = await ReadPageAsync(response.Content, cancellationToken).ConfigureAwait(false);
        return ParseTracks(html);
    }

    private static async Task<List<TranscriptTrack>> GetTracksFromInnertubeAsync(
        string videoId,
        HttpClient client,
        CancellationToken cancellationToken)
    {
        var body = JsonSerializer.Serialize(new
        {
            context = new
            {
                client = new
                {
                    clientName = "ANDROID",
                    clientVersion = AndroidClientVersion,
                    androidSdkVersion = 34,
                    hl = "en",
                    gl = "US"
                }
            },
            videoId,
            contentCheckOk = true,
            racyCheckOk = true
        });

        using var request = new HttpRequestMessage(HttpMethod.Post, "https://www.youtube.com/youtubei/v1/player?prettyPrint=false")
        {
            Content = new StringContent(body, Encoding.UTF8, "application/json")
        };
        request.Headers.UserAgent.Clear();
        request.Headers.UserAgent.ParseAdd($"com.google.android.youtube/{AndroidClientVersion} (Linux; U; Android 14) gzip");
        request.Headers.TryAddWithoutValidation("X-YouTube-Client-Name", "3");
        request.Headers.TryAddWithoutValidation("X-YouTube-Client-Version", AndroidClientVersion);
        request.Headers.Accept.ParseAdd("application/json");

        using var response = await client.SendAsync(request, HttpCompletionOption.ResponseHeadersRead, cancellationToken).ConfigureAwait(false);
        response.EnsureSuccessStatusCode();
        var json = await ReadPageAsync(response.Content, cancellationToken).ConfigureAwait(false);
        return ParseTracksFromJson(json);
    }

    /// <summary>
    /// Descarcă și formatează transcriptul pentru un track de subtitrare dat.
    /// </summary>
    internal static Task<string> GetTranscriptAsync(
        string baseUrl,
        bool includeTimestamps,
        CancellationToken cancellationToken = default) =>
        GetTranscriptAsync(baseUrl, includeTimestamps, Client, cancellationToken);

    internal static async Task<string> GetTranscriptAsync(
        string baseUrl,
        bool includeTimestamps,
        HttpClient client,
        CancellationToken cancellationToken = default)
    {
        // Formatul implicit (XML cu <text start="...">) este cel așteptat; eliminăm eventualul fmt=srv3 etc.
        baseUrl = Regex.Replace(baseUrl, @"&fmt=[^&]*", string.Empty);
        using var request = new HttpRequestMessage(HttpMethod.Get, baseUrl);
        request.Headers.Accept.ParseAdd("application/xml,text/xml,*/*");

        using var response = await client.SendAsync(request, HttpCompletionOption.ResponseHeadersRead, cancellationToken).ConfigureAwait(false);
        if (!response.IsSuccessStatusCode)
            throw new HttpRequestException(UiText.Format("Descărcarea transcriptului a eșuat cu eroarea {0}.", (int)response.StatusCode));

        var xml = await ReadPageAsync(response.Content, cancellationToken).ConfigureAwait(false);
        return ParseTranscriptXml(xml, includeTimestamps);
    }

    // ───────────────────────────────────────────────
    // Parsing intern
    // ───────────────────────────────────────────────

    internal static List<TranscriptTrack> ParseTracks(string html)
    {
        // Găsim blocul JSON ytInitialPlayerResponse din HTML-ul paginii YouTube.
        var markerIndex = html.IndexOf(PlayerResponseMarker, StringComparison.Ordinal);
        if (markerIndex < 0)
            throw new InvalidOperationException(UiText.Translate("Videoclipul nu are subtitrări disponibile sau pagina YouTube nu a putut fi citită."));

        var jsonStart = markerIndex + PlayerResponseMarker.Length;
        // Căutăm sfârșitul JSON-ului: `};` sau `};\n` sau `},\n` ori un punct de referință safe.
        var jsonEnd = FindJsonEnd(html, jsonStart);
        if (jsonEnd <= jsonStart)
            throw new InvalidOperationException(UiText.Translate("Videoclipul nu are subtitrări disponibile sau pagina YouTube nu a putut fi citită."));

        return ParseTracksFromJson(html[jsonStart..jsonEnd]);
    }

    internal static List<TranscriptTrack> ParseTracksFromJson(string json)
    {
        using var document = JsonDocument.Parse(json, new JsonDocumentOptions { MaxDepth = 64 });
        var root = document.RootElement;

        // Navigăm: captions → playerCaptionsTracklistRenderer → captionTracks
        if (!root.TryGetProperty("captions", out var captions)
            || !captions.TryGetProperty("playerCaptionsTracklistRenderer", out var tracklistRenderer)
            || !tracklistRenderer.TryGetProperty("captionTracks", out var captionTracks)
            || captionTracks.ValueKind != JsonValueKind.Array)
        {
            throw new InvalidOperationException(UiText.Translate("Videoclipul nu are subtitrări disponibile."));
        }

        var tracks = new List<TranscriptTrack>();
        foreach (var trackElement in captionTracks.EnumerateArray())
        {
            var languageCode = GetString(trackElement, "languageCode");
            var languageName = GetSimpleText(trackElement, "name");
            // baseUrl poate conține \u0026 în loc de & — JsonDocument deserializează automat escape-urile Unicode
            var trackBaseUrl = GetString(trackElement, "baseUrl");
            var kind = GetString(trackElement, "kind");
            var isAsr = kind == "asr";

            if (string.IsNullOrWhiteSpace(trackBaseUrl)) continue;
            languageName = ResolveLanguageName(languageCode, languageName);

            tracks.Add(new TranscriptTrack(languageCode, languageName, trackBaseUrl, isAsr));
        }

        if (tracks.Count == 0)
            throw new InvalidOperationException(UiText.Translate("Videoclipul nu are subtitrări disponibile."));

        // Sortăm: subtitrările manuale înaintea celor generate automat, apoi alfabetic după limbă.
        tracks.Sort((a, b) =>
        {
            var asr = a.IsAutoGenerated.CompareTo(b.IsAutoGenerated);
            return asr != 0 ? asr : string.Compare(a.LanguageName, b.LanguageName, StringComparison.CurrentCultureIgnoreCase);
        });

        return tracks;
    }

    internal static string ParseTranscriptXml(string xml, bool includeTimestamps)
    {
        if (string.IsNullOrWhiteSpace(xml))
            throw new InvalidOperationException(UiText.Translate("Transcriptul este gol sau nu a putut fi citit."));

        // Curățăm potențiale caractere de control din XML-ul returnat de YouTube.
        xml = Regex.Replace(xml, @"[\x00-\x08\x0B\x0C\x0E-\x1F]", string.Empty);

        XDocument doc;
        try
        {
            doc = XDocument.Parse(xml);
        }
        catch (Exception ex)
        {
            throw new InvalidOperationException(UiText.Format("Transcriptul nu a putut fi procesat: {0}", ex.Message));
        }

        // Două formate: <text start="secunde"> (clasic) și <p t="milisecunde"> (srv3).
        var segments = new List<(double Start, string Text)>();
        foreach (var element in doc.Descendants())
        {
            var name = element.Name.LocalName;
            double startSeconds;
            if (name == "text")
            {
                if (!double.TryParse(element.Attribute("start")?.Value, System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out startSeconds))
                    startSeconds = -1;
            }
            else if (name == "p")
            {
                if (double.TryParse(element.Attribute("t")?.Value, System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out var milliseconds))
                    startSeconds = milliseconds / 1000.0;
                else
                    startSeconds = -1;
            }
            else
            {
                continue;
            }

            // Unele răspunsuri conțin entități codificate de două ori (&amp;#39;), deci decodăm încă o dată.
            var text = WebUtility.HtmlDecode(element.Value);
            text = Regex.Replace(text, @"\s+", " ").Trim();
            if (text.Length == 0) continue;
            segments.Add((startSeconds, text));
        }

        if (segments.Count == 0)
            throw new InvalidOperationException(UiText.Translate("Transcriptul este gol sau nu a putut fi citit."));

        var sb = new StringBuilder(segments.Count * 80);
        foreach (var (start, text) in segments)
        {
            if (includeTimestamps && start >= 0)
            {
                var minutes = (int)(start / 60);
                var seconds = (int)(start % 60);
                sb.Append($"[{minutes:D2}:{seconds:D2}] ");
            }

            sb.AppendLine(text);
        }

        return sb.ToString().TrimEnd();
    }

    // ───────────────────────────────────────────────
    // Utilitare
    // ───────────────────────────────────────────────

    /// <summary>
    /// Găsește indexul de final al obiectului JSON care începe la <paramref name="start"/>,
    /// urmărind adâncimea parantezelor.
    /// </summary>
    private static int FindJsonEnd(string text, int start)
    {
        var depth = 0;
        var inString = false;
        var escaped = false;
        for (var i = start; i < text.Length; i++)
        {
            var c = text[i];
            if (escaped) { escaped = false; continue; }
            if (c == '\\' && inString) { escaped = true; continue; }
            if (c == '"') { inString = !inString; continue; }
            if (inString) continue;
            if (c == '{') { depth++; continue; }
            if (c == '}')
            {
                depth--;
                if (depth == 0) return i + 1;
            }
        }
        return -1;
    }

    /// <summary>
    /// Numele limbii afișat utilizatorului: doar limba (Română, English...), fără coduri, simboluri sau text tehnic.
    /// Se derivă din codul limbii; numele primit de la YouTube este folosit doar ca rezervă, curățat.
    /// </summary>
    internal static string ResolveLanguageName(string languageCode, string youTubeName)
    {
        var code = (languageCode ?? string.Empty).Trim();
        if (code.Length > 0)
        {
            try
            {
                var culture = System.Globalization.CultureInfo.GetCultureInfo(code);
                // Pentru variante regionale (pt-BR, en-GB) păstrăm doar limba, fără țară.
                if (!culture.IsNeutralCulture && culture.Parent.Name.Length > 0)
                    culture = culture.Parent;
                var display = culture.DisplayName?.Trim() ?? string.Empty;
                if (display.Length > 0 && culture.Name.Length > 0)
                    return char.ToUpper(display[0], System.Globalization.CultureInfo.CurrentUICulture) + display[1..];
            }
            catch (System.Globalization.CultureNotFoundException)
            {
                // Cod necunoscut: folosim numele primit de la YouTube.
            }
        }

        var cleaned = youTubeName ?? string.Empty;
        var cut = cleaned.IndexOfAny(new[] { '=', '(', '[', '{', '<', '|', '/', '\\', ':', ';' });
        if (cut >= 0) cleaned = cleaned[..cut];
        var dash = cleaned.IndexOf(" - ", StringComparison.Ordinal);
        if (dash >= 0) cleaned = cleaned[..dash];
        cleaned = Regex.Replace(cleaned, @"[^\p{L}\p{M}\s'’-]", " ");
        cleaned = Regex.Replace(cleaned, @"\s+", " ").Trim(' ', '-', '\'', '’');
        return cleaned.Length > 0 ? cleaned : code;
    }

    private static string GetSimpleText(JsonElement element, string property)
    {
        if (element.ValueKind != JsonValueKind.Object
            || !element.TryGetProperty(property, out var value))
            return string.Empty;

        if (value.ValueKind == JsonValueKind.String)
            return value.GetString() ?? string.Empty;

        if (value.ValueKind == JsonValueKind.Object
            && value.TryGetProperty("simpleText", out var simple)
            && simple.ValueKind == JsonValueKind.String)
            return simple.GetString() ?? string.Empty;

        // Răspunsurile Innertube folosesc {"runs":[{"text":"..."}]}.
        if (value.ValueKind == JsonValueKind.Object
            && value.TryGetProperty("runs", out var runs)
            && runs.ValueKind == JsonValueKind.Array)
        {
            var builder = new StringBuilder();
            foreach (var run in runs.EnumerateArray())
                builder.Append(GetString(run, "text"));
            return builder.ToString();
        }

        return string.Empty;
    }

    private static HttpClient CreateClient()
    {
        var handler = new HttpClientHandler
        {
            AutomaticDecompression = DecompressionMethods.All,
            AllowAutoRedirect = true,
            UseCookies = false,
            CheckCertificateRevocationList = true
        };
        var client = new HttpClient(handler) { Timeout = TimeSpan.FromSeconds(30) };
        client.DefaultRequestHeaders.UserAgent.ParseAdd(
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36");
        // Evită pagina de consimțământ YouTube (UE), care nu conține datele videoclipului.
        client.DefaultRequestHeaders.TryAddWithoutValidation("Cookie", "CONSENT=YES+1; SOCS=CAI");
        return client;
    }
}
